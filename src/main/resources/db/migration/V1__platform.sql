CREATE TABLE app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account VARCHAR(18) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 username VARCHAR(50) NOT NULL,
 avatar_url VARCHAR(1024), gender SMALLINT, phone VARCHAR(128), email VARCHAR(512),
 role VARCHAR(10) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER','ADMIN')),
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 memory_enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE platform_conversation (
 id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES app_user(id),
 title VARCHAR(100) NOT NULL DEFAULT '新对话',
 last_love BOOLEAN NOT NULL DEFAULT FALSE, last_task BOOLEAN NOT NULL DEFAULT FALSE,
 last_web BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX platform_conversation_owner ON platform_conversation(user_id, updated_at DESC);
CREATE TABLE platform_run (
 id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES app_user(id),
 conversation_id UUID NOT NULL REFERENCES platform_conversation(id) ON DELETE CASCADE,
 request_id UUID NOT NULL, request_hash VARCHAR(64) NOT NULL, session_id VARCHAR(100) NOT NULL,
 love BOOLEAN NOT NULL, task BOOLEAN NOT NULL, web BOOLEAN NOT NULL,
 memory_snapshot JSONB,
 status VARCHAR(20) NOT NULL DEFAULT 'RUNNING', cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,request_id)
);
CREATE UNIQUE INDEX platform_one_run ON platform_run(conversation_id) WHERE status='RUNNING';
CREATE TABLE platform_run_event (
 run_id UUID NOT NULL REFERENCES platform_run(id) ON DELETE CASCADE,
 sequence BIGINT NOT NULL, type VARCHAR(40) NOT NULL, payload JSONB NOT NULL,
 PRIMARY KEY(run_id,sequence)
);
CREATE TABLE platform_message (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id UUID NOT NULL REFERENCES platform_conversation(id) ON DELETE CASCADE,
 run_id UUID NOT NULL REFERENCES platform_run(id) ON DELETE CASCADE,
 role VARCHAR(12) NOT NULL CHECK (role IN ('USER','ASSISTANT','TOOL')),
 content TEXT NOT NULL, scope VARCHAR(12) NOT NULL CHECK (scope IN ('COMMON','LOVE','GENERAL')),
 love BOOLEAN NOT NULL, task BOOLEAN NOT NULL, web BOOLEAN NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED', context_valid BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX platform_message_history ON platform_message(conversation_id,id);
CREATE TABLE platform_memory (
 id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES app_user(id),
 source_message_id BIGINT NOT NULL REFERENCES platform_message(id) ON DELETE CASCADE,
 source_type VARCHAR(12) NOT NULL DEFAULT 'MESSAGE' CHECK(source_type IN ('MESSAGE','USER_EDIT')),
 subject VARCHAR(100) NOT NULL, fact_key VARCHAR(100) NOT NULL, fact_value VARCHAR(1000) NOT NULL,
 kind VARCHAR(12) NOT NULL CHECK(kind IN ('PREFERENCE','TEMPORARY','TASK','RETRACT')),
 scope VARCHAR(12) NOT NULL CHECK(scope IN ('COMMON','LOVE','GENERAL')),
 sensitive BOOLEAN NOT NULL DEFAULT FALSE, expires_at TIMESTAMPTZ,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','ACTIVE','SUPERSEDED','REVOKED')),
 version INT NOT NULL DEFAULT 1, replaces_id UUID REFERENCES platform_memory(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, confirmed_at TIMESTAMPTZ
);
CREATE INDEX platform_memory_owner ON platform_memory(user_id,status);
CREATE UNIQUE INDEX platform_memory_one_active ON platform_memory(user_id,subject,fact_key,kind,scope) WHERE status='ACTIVE';
CREATE TABLE platform_artifact (
 id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES app_user(id),
 conversation_id UUID NOT NULL, run_id UUID NOT NULL,
 scope VARCHAR(12) NOT NULL DEFAULT 'GENERAL' CHECK(scope IN ('COMMON','LOVE','GENERAL')),
 name VARCHAR(120) NOT NULL, storage_key VARCHAR(200) NOT NULL, media_type VARCHAR(100) NOT NULL,
 size_bytes BIGINT NOT NULL, deleted BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE platform_context_grant (
 id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES app_user(id),
 conversation_id UUID NOT NULL REFERENCES platform_conversation(id) ON DELETE CASCADE,
 target_run_id UUID, message_id BIGINT NOT NULL REFERENCES platform_message(id) ON DELETE CASCADE,
 used BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE platform_rate_event (bucket VARCHAR(150) NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX platform_rate_bucket ON platform_rate_event(bucket,created_at);
CREATE TABLE spring_session (
 primary_id CHAR(36) PRIMARY KEY, session_id CHAR(36) NOT NULL UNIQUE,
 creation_time BIGINT NOT NULL, last_access_time BIGINT NOT NULL,
 max_inactive_interval INT NOT NULL, expiry_time BIGINT NOT NULL, principal_name VARCHAR(100)
);
CREATE INDEX spring_session_expiry ON spring_session(expiry_time);
CREATE INDEX spring_session_principal ON spring_session(principal_name);
CREATE TABLE spring_session_attributes (
 session_primary_id CHAR(36) NOT NULL REFERENCES spring_session(primary_id) ON DELETE CASCADE,
 attribute_name VARCHAR(200) NOT NULL, attribute_bytes BYTEA NOT NULL,
 PRIMARY KEY(session_primary_id,attribute_name)
);
